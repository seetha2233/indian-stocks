"""RAG over our own model results + recent news, stored in Chroma.

Collections (local embeddings, no API key needed to index or search):
  news      one document per (article, stock)
  research  one card per stock (latest), plus model-performance,
            backtest and methodology documents

Answers are generated by the LLM from retrieved documents only, with
numbered citations.
"""

import json
from datetime import datetime, timedelta
from pathlib import Path

import chromadb
import pandas as pd
from sqlalchemy import text
from sqlalchemy.engine import Engine

from app.services import llm
from app.services.model import MODEL_DIR
from app.services.news import LOOKBACK_DAYS, MARKET, NEWS_TABLE
from app.services.signals import SIGNALS_TABLE, card


ROOT = Path(__file__).resolve().parents[3]

CHROMA_DIR = ROOT / "data" / "chroma"

BACKTEST_SUMMARY = ROOT / "data" / "backtest" / "summary.csv"

NEWS_KEEP_DAYS = LOOKBACK_DAYS

UPSERT_BATCH = 5000


def _client():
    return chromadb.PersistentClient(path=str(CHROMA_DIR))


def _collection(name: str):
    return _client().get_or_create_collection(
        name, metadata={"hnsw:space": "cosine"}
    )


def _clean_meta(meta: dict) -> dict:
    """Chroma metadata can't hold None."""
    return {k: v for k, v in meta.items() if v is not None and v == v}


# --- Indexing --------------------------------------------------------------

def index_news(engine: Engine) -> int:

    df = pd.read_sql(
        text(f"SELECT * FROM {NEWS_TABLE} WHERE published >= :cutoff"),
        engine,
        params={"cutoff": datetime.now() - timedelta(days=NEWS_KEEP_DAYS)},
        parse_dates=["published"]
    )

    col = _collection("news")

    ids = [f"{r.id}:{r.symbol}" for r in df.itertuples()]
    docs = [f"{r.title}. {r.summary or ''}".strip() for r in df.itertuples()]
    metas = [
        _clean_meta({
            "symbol": r.symbol.removesuffix(".NS"),
            "title": r.title,
            "source": r.source,
            "url": r.url,
            "published": f"{r.published:%Y-%m-%d %H:%M}",
            "published_ts": int(r.published.timestamp()),
            "sentiment": r.sentiment,
            "relevant": r.relevant,
        })
        for r in df.itertuples()
    ]

    # Chroma caps the number of records per call
    for i in range(0, len(ids), UPSERT_BATCH):
        col.upsert(
            ids=ids[i:i + UPSERT_BATCH],
            documents=docs[i:i + UPSERT_BATCH],
            metadatas=metas[i:i + UPSERT_BATCH],
        )

    cutoff = int((datetime.now() - timedelta(days=NEWS_KEEP_DAYS)).timestamp())
    col.delete(where={"published_ts": {"$lt": cutoff}})

    return len(df)


def _card_text(c: dict) -> str:

    s, f = c["scores"], c["fundamentals"]

    def pct(x):
        return "n/a" if x is None else f"{x * 100:.0f}%"

    lines = [
        f"{c['symbol']} ({c['name']}, {c['sector']}) stock card as of {c['as_of']}.",
        f"Price Rs {c['price']}. AI signal: {c['signal']}.",
        f"Entry zone Rs {c['entry_zone'][0]}-{c['entry_zone'][1]}; target 1 "
        f"Rs {c['target_1']} (median 1-week high); target 2 Rs {c['target_2']} "
        f"(median 20-day high); stop loss Rs {c['stop_loss']}; risk/reward "
        f"{c['risk_reward']}.",
        f"20-day upside probability (touch +5%): {pct(c['upside_prob_20d'])}. "
        f"Risk: {c['risk']} (predicted annual volatility "
        f"{pct(c['annual_volatility'])}).",
        f"Scores out of 100 vs all covered NSE stocks: technical {s['technical']}, "
        f"momentum {s['momentum']}, fundamental {s['fundamental']}, "
        f"news {s['news'] if s['news'] is not None else 'n/a'}, "
        f"composite {s['composite']}.",
        f"Fundamentals: P/E {f['pe']}, P/B {f['pb']}, ROE {pct(f['roe'])}; "
        f"valuation {f['valuation']}, quality {f['quality']}, growth "
        f"{f['growth']}, balance sheet {f['balance_sheet']} (sector-relative).",
        "Reasons: " + " ".join(f"- {w}." for w in c["why"]),
    ]

    return "\n".join(lines)


def _performance_docs() -> list[tuple[str, str, str]]:
    """(id, title, text) for model performance, backtest, methodology."""

    docs = []

    metrics_path = MODEL_DIR / "metrics.json"

    if metrics_path.exists():

        m = json.loads(metrics_path.read_text())
        start, end = m["test_period"]

        lines = [f"Model test results on unseen data, {start} to {end}."]

        for target, t in m["targets"].items():
            if "auc" in t:
                lines.append(
                    f"{target}: AUC {t['auc']:.2f}; mean predicted "
                    f"{t['mean_predicted']:.0%} vs actual {t['all_actual']:.0%}."
                )
            else:
                lines.append(
                    f"{target}: MAE {t['mae'] * 100:.2f}% vs baseline "
                    f"{t['baseline_mae'] * 100:.2f}%; daily rank correlation "
                    f"{t['rank_ic']:.2f}"
                    + (f"; direction accuracy {t['direction_accuracy']:.0%}"
                       if "direction_accuracy" in t else "")
                    + "."
                )

        docs.append(("doc:model_performance", "Model performance", "\n".join(lines)))

    if BACKTEST_SUMMARY.exists():

        b = pd.read_csv(BACKTEST_SUMMARY, index_col=0)

        curves = pd.read_csv(BACKTEST_SUMMARY.parent / "equity_curves.csv", index_col=0)
        days = len(curves)

        lines = [
            f"Walk-forward backtest over {days} trading days ({curves.index[0]} "
            f"to {curves.index[-1]}): models retrained every 10 trading days on "
            f"known outcomes only, buy at next open, 0.3% round-trip costs, "
            f"liquid stocks only (at least Rs 5 crore traded a day):"
        ]
        for name, r in b.iterrows():
            lines.append(
                f"{name}: {r['total_return'] * 100:+.1f}% after costs "
                f"({r['gross_return'] * 100:+.1f}% before), max drawdown "
                f"{r['max_drawdown'] * 100:.1f}%."
            )

        model = b[b.index.str.startswith("Model")]["total_return"]
        hold = b[b.index.str.startswith("Buy & hold")]["total_return"]

        if len(model) and len(hold):
            best, bh = model.max(), hold.iloc[0]
            verdict = "beat" if best > bh else "did not beat"
            lines.append(
                f"Conclusion: the best model strategy ({model.idxmax()}, "
                f"{best * 100:+.1f}%) {verdict} buy-and-hold ({bh * 100:+.1f}%) "
                f"after costs."
                + (
                    f" With only {days} trading days this is not statistically "
                    f"reliable; treat it as a hypothesis for the forward "
                    f"signal tracker to confirm."
                    if days < 120 else ""
                )
            )

        docs.append(("doc:backtest", "Backtest results", "\n".join(lines)))

    docs.append((
        "doc:methodology",
        "How stock cards are built",
        "Stock cards cover all NSE main-board stocks (EQ and BE series) "
        "using at most 6 months of daily prices. XGBoost models predict the median 1-week and 20-day high "
        "(targets 1 and 2), the chance of touching +5% within 20 trading "
        "days, and next-20-day volatility (the risk model; risk is the "
        "Low/Medium/High tercile). Entry zone is today's price down to "
        "0.5 x ATR; stop loss is 2 x ATR below price. Technical and momentum "
        "scores are percentile ranks within all covered stocks today; the "
        "fundamental score ranks valuation, quality, growth and leverage "
        "against sector peers; the news score is recency-weighted LLM "
        "sentiment of the last 5 days of news. WATCH also requires at least "
        "Rs 5 crore traded a day. The WATCH / NEUTRAL / AVOID signal is a "
        "transparent rule on those scores and has not been validated as a "
        "predictor. The models estimate price range and volatility far "
        "better than direction."
    ))

    return docs


def index_research(engine: Engine) -> int:

    signals = pd.read_sql(
        text(
            f"SELECT * FROM {SIGNALS_TABLE} WHERE timestamp = "
            f"(SELECT max(timestamp) FROM {SIGNALS_TABLE})"
        ),
        engine,
        parse_dates=["timestamp"]
    )

    cards = [card(r) for r in signals.to_dict("records")]

    ids = [f"card:{c['symbol']}" for c in cards]
    docs = [_card_text(c) for c in cards]
    metas = [
        {"symbol": c["symbol"], "type": "card", "title": f"{c['symbol']} stock card",
         "published": c["as_of"]}
        for c in cards
    ]

    for doc_id, title, body in _performance_docs():
        ids.append(doc_id)
        docs.append(body)
        metas.append({"type": "doc", "title": title})

    _collection("research").upsert(ids=ids, documents=docs, metadatas=metas)

    return len(ids)


# --- Retrieval -------------------------------------------------------------

def _hits(result: dict, kind: str) -> list[dict]:

    out = []

    for doc, meta, dist in zip(
        result["documents"][0], result["metadatas"][0], result["distances"][0]
    ):
        out.append({
            "type": kind,
            "title": meta.get("title"),
            "text": doc,
            "symbol": meta.get("symbol"),
            "source": meta.get("source"),
            "url": meta.get("url"),
            "published": meta.get("published"),
            "sentiment": meta.get("sentiment"),
            "score": round(1 - dist, 3),
        })

    return out


def retrieve(question: str, symbol: str | None = None, k_news: int = 8) -> list[dict]:

    symbol = symbol.upper().removesuffix(".NS") if symbol else None

    research = _collection("research")
    news = _collection("news")

    sources = []

    if symbol:
        got = research.get(ids=[f"card:{symbol}"])
        if got["ids"]:
            sources.append({
                "type": "card",
                "title": f"{symbol} stock card",
                "text": got["documents"][0],
                "symbol": symbol,
                "published": got["metadatas"][0].get("published"),
            })

    # Model / backtest / methodology context
    sources += _hits(
        research.query(query_texts=[question], n_results=2, where={"type": "doc"}),
        "research"
    )

    if not symbol:
        sources += _hits(
            research.query(query_texts=[question], n_results=3, where={"type": "card"}),
            "card"
        )

    news_filter = {"symbol": symbol} if symbol else None

    n_news = news.count()

    if n_news:
        sources += _hits(
            news.query(
                query_texts=[question],
                n_results=min(k_news, n_news),
                where=news_filter,
            ),
            "news"
        )

    return sources


def ask(question: str, symbol: str | None = None) -> dict:

    sources = retrieve(question, symbol)

    if not llm.available():
        return {
            "answer": None,
            "note": "LLM not configured (set OPENAI_API_KEY); showing retrieved sources only.",
            "sources": sources,
        }

    prompt_sources = [
        {k: s.get(k) for k in ("type", "title", "text", "source", "published")}
        for s in sources
    ]

    out = llm.answer_question(question, prompt_sources)

    return {"answer": out["answer"], "cited": out["cited"], "sources": sources}
